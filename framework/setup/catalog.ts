/** Problems with the manual cases' `setup`: unknown recipe, invalid params, or a body that arranges another way. */
export function checkCases(cases: TestCase[], body: (tc: TestCase) => string): string[] {
  const problems: string[] = [];
  for (const tc of cases) {
    if (tc.status === 'deprecated') continue;
    if (!tc.setup) {
      problems.push(`${tc.id}: no \`setup\` (add the recipe that arranges its preconditions)`);
      continue;
    }
    if (!isRecipe(tc.setup.recipe)) {
      problems.push(`${tc.id}: setup.recipe "${tc.setup.recipe}" is not a recipe (${Object.keys(RECIPES).join(', ')})`);
      continue;
    }
    const parsed = RECIPES[tc.setup.recipe].params.safeParse(tc.setup.params);
    if (!parsed.success)
      problems.push(`${tc.id}: setup params: ${z.prettifyError(parsed.error).replaceAll('\n', ' ')}`);
    const text = body(tc);
    if (/seed:session|set up over the API\b/.test(text))
      problems.push(`${tc.id}: preconditions describe their own setup (use \`bun run qa:arrange --case ${tc.id}\`)`);
    if (!text.includes(`qa:arrange --case ${tc.id}`))
      problems.push(`${tc.id}: preconditions do not name \`bun run qa:arrange --case ${tc.id} --name <session>\``);
  }
  return problems;
}
