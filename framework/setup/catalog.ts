/**
 * The recipes as knowledge: renders knowledge/setup/SETUP-RECIPES.md from framework/setup/recipes.ts (so the
 * document can't drift from the code), and checks that every manual test case arranges through a recipe.
 */

import { z } from 'zod';
import type { TestCase } from '@qa/vault';
import { Cards } from '@data/cards';
import { RECIPES, isRecipe, type Recipe } from '@setup/recipes';

export const CATALOG_PATH = 'knowledge/setup/SETUP-RECIPES.md';

type Param = { name: string; type: string; default: string; doc: string };

function params(schema: z.ZodObject): Param[] {
  return Object.entries(schema.shape).map(([name, field]) => {
    let inner = field as z.ZodType;
    let fallback = 'required';
    if (inner instanceof z.ZodDefault) {
      fallback = `\`${String(inner.def.defaultValue)}\``;
      inner = inner.unwrap() as z.ZodType;
    }
    if (inner instanceof z.ZodOptional) {
      fallback = 'none';
      inner = inner.unwrap() as z.ZodType;
    }
    const type = inner instanceof z.ZodEnum ? inner.options.join(' \\| ') : inner.def.type;
    return { name, type, default: fallback, doc: (field as z.ZodType).description ?? '' };
  });
}

function section(id: string, r: Recipe): string {
  const rows = params(r.params);
  const example = `bun run qa:arrange ${id} --name <session>${r.example ? ` ${r.example}` : ''}`;
  return [
    `## Recipe: ${id}`,
    '',
    r.summary,
    '',
    `- Creates data: ${r.seeds ? 'yes (not allowed on a read-only environment)' : 'no (runs on live too)'}`,
    `- Steps start on: \`${r.lands}\``,
    `- Typical for: ${r.covers.join(', ')}`,
    `- Example: \`${example}\``,
    '',
    ...(rows.length
      ? [
          '| Param | Type | Default | Meaning |',
          '| --- | --- | --- | --- |',
          ...rows.map((p) => `| \`${p.name}\` | ${p.type} | ${p.default} | ${p.doc} |`),
        ]
      : ['No parameters.']),
    '',
  ].join('\n');
}

